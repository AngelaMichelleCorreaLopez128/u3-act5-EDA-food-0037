import pandas as pd
import matplotlib.pyplot as plt
# Angela Correa NC = 0037
# 1. Leer el archivo CSV
df_food_india = pd.read_csv('indian_food.csv')
print("\n--- DATOS LEÍDOS DESDE CSV, comida India 0037 ---")
print(df_food_india)
print("\n--- Mostrar Nombre comida + ingredientes 0037 ---")
recetas = df_food_india[['name', 'ingredients']]
print(recetas)
print("\n--- Tiempo de cocinado mostrar 10 registros con head 0037 ---")
nombre_y__hora = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y__hora)
print("\n---Grafica comida (x) Tiempo de cocinando (Y) ---")
print("\n---Grafica comida (x) texto a 30 grados ---")
nombre_y__hora.plot.bar(x='name',y='cook_time', rot=30)
plt.title('Comida tipica de India Angela 0037')
plt.xlabel('Nombre platillo')
plt.ylabel('tiempo de cocinado')
plt.show()
print("gráfica de varias columnas Angela 0037")
nombre_y__hora = df_food_india[['name', 'prep_time', 'cook_time']].head(10)
nombre_y__hora.plot.bar(x='name', rot=30)
plt.title('Grafica de dos columnas Angela 0037')
plt.xlabel('Nombre platillo')
plt.ylabel('tiempo de cocinado prep y comida')
plt.show()
print("Gráficas apiladas una tras otra verticalmente 0037")
nombre_y__hora.plot.bar(x='name', stacked=True, rot=30)
plt.title('Grafica apiladas Angela 0037')
plt.xlabel('Nombre platillo')
plt.ylabel('tiempo de cocinado prep y comida')
plt.show()